#!/usr/bin/env python3
"""Generate the DSH academic research preset from the installed Harness.

The preset is DERIVED from the shipped `preset-standard` plugin list, so it
follows the installed DSH version instead of being a hand-copied snapshot. On
top of that this script:

  * replaces the coding-assistant persona with an academic one;
  * mounts the CNKI MCP server that maps 知网空间 links to kns.cnki.net links
    (see ../servers/cnki-search), plus the public arXiv / PubMed /
    Semantic Scholar sources, and optionally the nature-academic-search server;
  * disables the plugin-manager tools so an academic session cannot install
    plugins on its own.

Why derive instead of ship a fixed list: `preset-standard` changes between DSH
releases (plugin ids, config keys, new plugins). A hand-copied list breaks the
whole preset when one row no longer resolves, because a preset only mounts when
every enabled row settles.

Typical use, after `git clone`:

    # 1. derive and splice into your profile's patch layer (backup written first)
    python preset/gen-preset.py --from-cli --update-patch "$DSH_HOME/profiles/desktop/cordis.patch.yml"

    # 2. point at this repo's CNKI server instead of the default $DSH_HOME/cnki-kns
    python preset/gen-preset.py --from-cli --cnki-dir "<repo>/servers/cnki-search" \
        --update-patch "$DSH_HOME/profiles/desktop/cordis.patch.yml"

    # 3. check for drift after upgrading DSH
    python preset/gen-preset.py --from-cli --check "$DSH_HOME/profiles/desktop/cordis.patch.yml"

The `desktop` profile is managed exclusively by the Electron application and
refuses `--dump-default-config`, so `--from-cli` derives from the CLI-managed
`web` profile, which ships the same bundles. A dump file can be passed instead
when the CLI is unavailable:

    dsh --profile web --dump-default-config > dump.yml
    python preset/gen-preset.py dump.yml --preset-only preset.yml
"""

from __future__ import annotations

import argparse
import datetime
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

DEFAULT_DUMP_PROFILE = "web"
PRESET_ID = "preset-academic"
PRESET_KEY = "academic"
PRESET_NAME = "学术研究"
PRESET_DESCRIPTION = "文献检索、综述与学术写作的研究助手"
PRESET_ORDER = 0

# Prompt variables dsh-agent-loop registers. Any other {{variable}} in a preset
# section throws "unknown prompt variable" at render time, which keeps the whole
# session from starting.
KNOWN_PROMPT_VARIABLES = {"model", "provider"}

MARK_BEGIN = "# >>> preset-academic >>> generated by gen-preset.py -- do not edit inside the markers"
MARK_END = "# <<< preset-academic <<<"

PATCH_HEADER = """\
# DSH profile patch layer, applied after every bundle layer: a top-level YAML
# array of loader patch entries (id-targeted overrides, disables, inserts).
#
# The preset-academic block below is generated by gen-preset.py from the
# installed DSH's shipped preset-standard. Re-derive it after every DSH upgrade,
# do not hand-patch the plugin list:
#
#   python <repo>/preset/gen-preset.py --from-cli \\
#       --cnki-dir <repo>/servers/cnki-search \\
#       --update-patch <this file>
#
# Entries outside the markers are your own and are left untouched.
"""

ACADEMIC_PERSONA = (
    "You are an academic research assistant powered by the {{model}} model. "
    "Ground every claim about the literature in output actually returned by the "
    "available tools (mcp__cnki__*, mcp__arxiv__*, mcp__pubmed__*, "
    "mcp__semantic-scholar__*, read_page, web_search); never fabricate a title, "
    "author, year, DOI, venue, volume or page range, and say plainly when a tool "
    "cannot confirm something. Distinguish what a source states from your own "
    "inference, quote precisely where wording matters, and answer in the user's "
    "language. Treat publication status as part of the finding. Label a record as "
    "preprint, conference paper or journal article as the source reports it, and "
    "let the current date from the time context decide what counts as recent "
    "rather than your training cutoff. For every CNKI record, cite the link in "
    "its url field (a kns.cnki.net main-site link, which is what can be opened "
    "and downloaded from) and never the space_url field or any cnki.com.cn "
    "知网空间 link; if a record carries no kns.cnki.net link, say the main-site "
    "link is unavailable instead of offering the 知网空间 page. The CNKI source "
    "exposes no DOI, so never infer one from it. Identify a CNKI record by its "
    "space_url or its dbcode and filename, never by its title, since a CNKI title "
    "search is fuzzy recall; when a record is already known by a link, re-read it "
    "with get_record instead of searching again. Never hand-build a "
    "kns.cnki.net link from a 知网空间 URL -- an invented filename still answers "
    "HTTP 200 -- so take dbcode and filename only from tool output."
)

CNKI_HEADER = """\
          # ===================== literature sources (MCP) =====================
          # Tool names are mcp__<serverName>__<tool>. A preset is mounted eagerly
          # when the host starts, so these processes live as long as the app runs;
          # only sessions that select this preset see the tools.
          #
          # --- CNKI 题录检索 --------------------------------------------
          # Server: servers/cnki-search in this repo, a fork of
          # https://github.com/Biogod2020/cnki-search that maps the returned link
          # from 知网空间 (cnki.com.cn) to the download-capable main site:
          #   https://kns.cnki.net/kcms/detail/detail.aspx?dbcode=<dbcode>&filename=<filename>
          # The original 知网空间 link is kept in space_url for get_record only.
          # The endpoint carries no DOI and no full text; whether a PDF can be
          # downloaded depends on your institution's IP / login state, not on the
          # link itself. See servers/cnki-search/CHANGES.md for the mapping rules.
          #
          # failOnStartupError stays false for every source: they are started from
          # remote packages (uvx / npx) or a local venv, and a transient failure
          # would otherwise veto the whole session with
          # "initial connection or tool synchronization failed". With false, the
          # source's tools simply do not appear and the session keeps working.
"""

PUBMED_HEADER = """\
          # --- PubMed / Europe PMC -------------------------------------
          # npx on Windows is a .cmd shim, which Node's spawn cannot resolve
          # directly (bare 'npx' gives ENOENT, 'npx.cmd' gives EINVAL), so it is
          # forwarded through cmd /c.
"""

SEMANTIC_SCHOLAR_HEADER = """\
          # --- Semantic Scholar ----------------------------------------
          # Citation graph, similar-paper recommendations and export_bibtex.
          # Anonymous calls share a rate-limited pool; set
          # SEMANTIC_SCHOLAR_API_KEY in the host environment to raise the limit.
          # mcp-client strips environment variables whose name contains KEY, so
          # the variable has to be merged back explicitly here.
"""

ACADEMIC_SEARCH_HEADER = """\
          # --- nature-academic-search ----------------------------------
          # Optional. Unified CrossRef / PubMed / arXiv / Scopus / ScienceDirect
          # search from https://github.com/Yuan1z0825/nature-skills, run from its
          # own .venv (no package pull at startup). Pass
          # --academic-search-dir to enable; the server must import utils and
          # sources as top-level modules, hence cwd.
"""

PLUGIN_MANAGER_NOTE = "academic sessions do not install plugins on the model's behalf"


def q(value: str | Path) -> str:
    """Render one YAML scalar for a file-system path."""
    text = Path(value).expanduser().as_posix()
    if not text:
        raise SystemExit("empty path")
    return '"' + text.replace('"', '\\"') + '"'


def resolve_dsh_home() -> Path:
    env = os.environ.get("DSH_HOME")
    return Path(env).expanduser() if env else Path.home() / ".dsh"


def cli_dump(profile: str) -> str:
    """Return `dsh --profile <profile> --dump-default-config` output."""
    exe = shutil.which("dsh")
    if exe is None:
        raise SystemExit("dsh CLI not found on PATH; pass a dump file instead")
    argv = [exe]
    if Path(exe).suffix.lower() in {".cmd", ".bat"}:
        argv = [os.environ.get("COMSPEC", "cmd.exe"), "/c", exe]
    argv += ["--profile", profile, "--dump-default-config"]
    proc = subprocess.run(argv, capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        raise SystemExit(
            f"dsh dump failed (exit {proc.returncode}): {proc.stderr.strip()}"
        )
    return proc.stdout


def extract_preset_standard(lines: list[str]) -> list[str]:
    """Return the raw YAML block of the shipped `preset-standard` entry."""
    start = next(
        i for i, line in enumerate(lines) if line.startswith("- id: preset-standard")
    )
    end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith("- id: "))
    block = lines[start:end]
    while block and not block[-1].strip():
        block.pop()
    return block


def mcp_plugins(
    cnki_dir: Path,
    academic_search_dir: Path | None,
) -> str:
    """Render the literature-source rows, indented for preset.plugins."""
    rows = [CNKI_HEADER]
    rows.append(
        f"""\
          - id: mcp-cnki
            name: '@deepseek-ai/dsh-mcp-client'
            config:
              serverName: cnki
              transport: stdio
              command: uv
              args:
                - run
                - --directory
                - {q(cnki_dir)}
                - cnki-search
              toolCallTimeoutMs: 60000
              failOnStartupError: false
"""
    )
    rows.append(
        """\
          # --- arXiv ---------------------------------------------------
          # Published PyPI package; full-text and section-level reading.
          - id: mcp-arxiv
            name: '@deepseek-ai/dsh-mcp-client'
            config:
              serverName: arxiv
              transport: stdio
              command: uvx
              args:
                - arxiv-mcp-server
              toolCallTimeoutMs: 60000
              failOnStartupError: false
"""
    )
    rows.append(PUBMED_HEADER)
    rows.append(
        """\
          - id: mcp-pubmed
            name: '@deepseek-ai/dsh-mcp-client'
            config:
              serverName: pubmed
              transport: stdio
              command: cmd
              args:
                - /c
                - npx
                - -y
                - '@cyanheads/pubmed-mcp-server'
              toolCallTimeoutMs: 60000
              failOnStartupError: false
"""
    )
    rows.append(SEMANTIC_SCHOLAR_HEADER)
    rows.append(
        """\
          - id: mcp-semantic-scholar
            name: '@deepseek-ai/dsh-mcp-client'
            config:
              serverName: semantic-scholar
              transport: stdio
              command: uvx
              args:
                - --from
                - git+https://github.com/akapet00/semantic-scholar-mcp
                - semantic-scholar-mcp
              env: !!js 'process.env.SEMANTIC_SCHOLAR_API_KEY ? { SEMANTIC_SCHOLAR_API_KEY: process.env.SEMANTIC_SCHOLAR_API_KEY } : {}'
              toolCallTimeoutMs: 60000
              failOnStartupError: false
"""
    )
    if academic_search_dir is not None:
        rows.append(ACADEMIC_SEARCH_HEADER)
        python = academic_search_dir / (".venv/Scripts/python.exe" if os.name == "nt" else ".venv/bin/python")
        rows.append(
            f"""\
          - id: mcp-academic-search
            name: '@deepseek-ai/dsh-mcp-client'
            config:
              serverName: academic-search
              transport: stdio
              command: {q(python)}
              args:
                - academic_search_server.py
              cwd: {q(academic_search_dir)}
              env: !!js 'Object.fromEntries(Object.entries({{ PUBMED_EMAIL: process.env.PUBMED_EMAIL, NCBI_API_KEY: process.env.NCBI_API_KEY }}).filter(([, v]) => Boolean(v)))'
              # CrossRef/PubMed/arXiv run concurrently; one slow source (arXiv
              # API in practice) gates the whole call, so allow more time.
              toolCallTimeoutMs: 120000
              failOnStartupError: false
"""
        )
    return "".join(rows)


def build_preset(block: list[str], cnki_dir: Path, skill_dir: Path | None,
                 academic_search_dir: Path | None) -> str:
    # Nest one level deeper: the preset becomes an `insert` list item.
    text = "\n".join(("    " + line) if line.strip() else "" for line in block)

    # 0.1.x shipped a `suffix: Your working directory is {{cwd}}.` line whose
    # variable 0.2.x no longer registers; drop it defensively so a dump taken
    # from an older profile cannot poison the preset.
    text = re.sub(
        r"^\s*suffix: Your working directory is \{\{cwd\}\}\.\s*\n", "", text, flags=re.M
    )
    text = re.sub(r"^(\s*)- id: preset-standard$", rf"\1- id: {PRESET_ID}", text, count=1, flags=re.M)
    text = re.sub(r"^(\s*)id: standard$", rf"\1id: {PRESET_KEY}", text, count=1, flags=re.M)
    text = re.sub(r"^(\s*)order: 1$", rf"\1order: {PRESET_ORDER}", text, count=1, flags=re.M)
    text = re.sub(
        r"^(\s*)id: academic\n",
        lambda m: (
            f"{m.group(1)}id: {PRESET_KEY}\n"
            f"{m.group(1)}name: {PRESET_NAME}\n"
            f"{m.group(1)}description: {PRESET_DESCRIPTION}\n"
        ),
        text,
        count=1,
        flags=re.M,
    )

    for bad in (": ", " #"):
        if bad in ACADEMIC_PERSONA:
            raise SystemExit(
                f"ACADEMIC_PERSONA must not contain {bad!r}: it breaks a YAML plain scalar"
            )
    old_prefix = "prefix: You are a coding agent powered by the {{model}} model."
    if old_prefix not in text:
        raise SystemExit("preset-standard persona prefix not found; dump changed?")
    text = text.replace(old_prefix, "prefix: " + ACADEMIC_PERSONA, 1)

    text, n = re.subn(
        r"(^(\s*)- id: tool-plugin-manager\n\s*name: '@deepseek-ai/dsh-plugin-manager/tools'\n\s*disabled: ).*$",
        lambda m: f"{m.group(1)}true  # {PLUGIN_MANAGER_NOTE}",
        text,
        count=1,
        flags=re.M,
    )
    if n != 1:
        raise SystemExit("tool-plugin-manager row not found; dump changed?")

    if skill_dir is not None:
        text, n = re.subn(
            r"^(\s*)- id: skill-filesystem\n(\s*)name: '@deepseek-ai/dsh-skill-filesystem'\n",
            lambda m: (
                f"{m.group(1)}- id: skill-filesystem\n"
                f"{m.group(2)}name: '@deepseek-ai/dsh-skill-filesystem'\n"
                f"{m.group(2)}config:\n"
                f"{m.group(2)}  customSkillDirs:\n"
                f"{m.group(2)}    - {q(skill_dir)}\n"
            ),
            text,
            count=1,
            flags=re.M,
        )
        if n != 1:
            raise SystemExit("skill-filesystem row not found; dump changed?")

    return text + "\n" + mcp_plugins(cnki_dir, academic_search_dir).rstrip("\n") + "\n"


def validate_prompt_variables(text: str) -> None:
    used = set(re.findall(r"\{\{([A-Za-z_][A-Za-z0-9_]*)\}\}", text))
    unknown = used - KNOWN_PROMPT_VARIABLES
    if unknown:
        raise SystemExit(
            "unknown prompt variable(s) "
            + ", ".join(sorted(unknown))
            + f"; registered: {', '.join(sorted(KNOWN_PROMPT_VARIABLES))}"
        )


def build_block(args) -> str:
    dump_text = cli_dump(args.profile) if args.from_cli else args.dump.read_text(encoding="utf-8-sig")
    lines = dump_text.lstrip("\ufeff").splitlines()
    preset = build_preset(
        extract_preset_standard(lines),
        cnki_dir=Path(args.cnki_dir).expanduser(),
        skill_dir=Path(args.skill_dir).expanduser() if args.skill_dir else None,
        academic_search_dir=(
            Path(args.academic_search_dir).expanduser() if args.academic_search_dir else None
        ),
    )
    validate_prompt_variables(preset)
    return "- insert:\n" + preset


def marked_span(text: str) -> tuple[list[str], int, int]:
    lines = text.splitlines()
    try:
        begin = next(i for i, line in enumerate(lines) if line.strip() == MARK_BEGIN.strip())
        end = next(i for i, line in enumerate(lines) if line.strip() == MARK_END.strip())
    except StopIteration:
        raise SystemExit(f"markers not found; expected '{MARK_BEGIN}' and '{MARK_END}'")
    if end <= begin:
        raise SystemExit("preset-academic markers are out of order")
    return lines, begin, end


def normalized(text: str) -> str:
    return "\n".join(line.rstrip() for line in text.strip("\n").splitlines())


def spliced(text: str, block: str) -> str:
    lines, begin, end = marked_span(text)
    out = lines[: begin + 1] + block.rstrip("\n").splitlines() + lines[end:]
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    home = resolve_dsh_home()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dump", nargs="?", type=Path, help="output of dsh --dump-default-config")
    ap.add_argument("--from-cli", action="store_true", help=f"derive from `dsh --profile {DEFAULT_DUMP_PROFILE} --dump-default-config`")
    ap.add_argument("--profile", default=DEFAULT_DUMP_PROFILE, help="profile used as the derivation source")
    ap.add_argument("--cnki-dir", default=str(home / "cnki-kns"), help="path to servers/cnki-search (default: $DSH_HOME/cnki-kns)")
    ap.add_argument("--skill-dir", default=None, help="register this skill root as a custom root (default: leave preset-standard's skill-filesystem alone)")
    ap.add_argument("--academic-search-dir", default=None, help="enable the optional nature-academic-search MCP server")
    ap.add_argument("--out", type=Path, help="write a standalone patch file")
    ap.add_argument("--preset-only", type=Path, help="write only the preset block")
    ap.add_argument("--update-patch", type=Path, metavar="PATCH", help="splice the block into PATCH between its markers (backup first)")
    ap.add_argument("--check", type=Path, metavar="PATCH", help="exit non-zero when PATCH's marked block is stale")
    ap.add_argument("--set-default", action="store_true", help="--out only: make the academic preset the default for new sessions")
    args = ap.parse_args()

    if not args.from_cli and args.dump is None:
        ap.error("need a dump file or --from-cli")
    if not any([args.out, args.preset_only, args.update_patch, args.check]):
        ap.error("need --out, --preset-only, --update-patch or --check")

    block = build_block(args)
    exit_code = 0

    if args.check is not None:
        current = args.check.read_text(encoding="utf-8-sig")
        _, begin, end = marked_span(current)
        current_block = "\n".join(current.splitlines()[begin + 1 : end]).strip("\n")
        stale = normalized(current_block) != normalized(block)
        if stale:
            print(f"{args.check}: preset-academic block is STALE; re-run with --update-patch", file=sys.stderr)
            exit_code = 1
        else:
            print(f"{args.check}: preset-academic block matches the installed DSH")

    if args.update_patch is not None:
        target = args.update_patch
        current = target.read_text(encoding="utf-8-sig")
        updated = spliced(current, block)
        if normalized(updated) == normalized(current):
            print(f"{target}: already up to date")
        else:
            stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
            backup = target.with_suffix(target.suffix + f".bak-preset-{stamp}")
            shutil.copy2(target, backup)
            target.write_text(updated, encoding="utf-8")
            print(f"{target}: wrote {len(block.splitlines())}-line block (backup {backup.name})")

    if args.preset_only is not None:
        args.preset_only.write_text(block, encoding="utf-8")
        print(f"wrote {args.preset_only} ({len(block.splitlines())} lines)")

    if args.out is not None:
        out = PATCH_HEADER + "\n" + MARK_BEGIN + "\n" + block + MARK_END + "\n"
        if args.set_default:
            out += (
                "\n# Make the academic preset the default for new sessions.\n"
                "- id: agent-preset-registry\n"
                "  name: '@deepseek-ai/dsh-agent-preset-registry'\n"
                "  config:\n"
                "    default: academic\n"
            )
        args.out.write_text(out, encoding="utf-8")
        print(f"wrote {args.out} ({len(out.splitlines())} lines)")

    return exit_code


if __name__ == "__main__":
    sys.exit(main())
